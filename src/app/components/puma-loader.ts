interface Pixel {
  readonly x: number;
  readonly y: number;
}

function toPixels(rows: readonly string[]): readonly Pixel[] {
  const pixels: Pixel[] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x += 1) {
      if (row[x] === '#') {
        pixels.push({ x, y });
      }
    }
  });
  return pixels;
}

const FRAMES = FRAME_DATA.map(toPixels);

